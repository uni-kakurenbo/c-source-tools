use crate::c_source::{Scanner, directives, lex};
pub use crate::layout::SectionOrder;
use crate::layout::{ordered_headers, ordered_sources};
use crate::modules::{Graph, Project, module_names};
use crate::{Result, read_text};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

/// Bundle text, prepared generated includes, and the resolved module graph.
pub struct Rendered {
    pub text: String,
    pub generated: BTreeMap<String, String>,
    pub graph: Graph,
}

struct Expander<'a> {
    project: &'a Project,
    graph: &'a Graph,
    generated: &'a BTreeMap<String, String>,
    headers: Vec<(&'a str, String)>,
    seen: BTreeSet<String>,
    system_headers: BTreeSet<String>,
}

fn strip_pragma_once(text: &str) -> Result<String> {
    let mut stripped = String::new();
    let mut cursor = 0;

    for directive in directives(text)? {
        let logical = directive.text.replace("\\\n", "");
        let tokens = lex(&logical, false)?;
        if !tokens
            .iter()
            .map(|token| token.text.as_str())
            .eq(["#", "pragma", "once"])
        {
            continue;
        }

        let line_start = text[..directive.start]
            .rfind('\n')
            .map_or(0, |offset| offset + 1);
        let start = if text[line_start..directive.start].trim().is_empty() {
            line_start
        } else {
            directive.start
        };

        stripped.push_str(&text[cursor..start]);
        cursor = directive.end;
    }

    stripped.push_str(&text[cursor..]);

    Ok(stripped)
}

impl Expander<'_> {
    fn expand_generated(&mut self, content: &str) -> Result<String> {
        let mut expanded = String::new();
        let mut cursor = 0;
        for directive in directives(content)? {
            if let Some(header) = directive
                .text
                .trim()
                .strip_prefix("#include <")
                .and_then(|header| header.strip_suffix('>'))
            {
                self.system_headers.insert(header.to_owned());
                expanded.push_str(&content[cursor..directive.start]);
                cursor = directive.end;
            }
        }
        expanded.push_str(&content[cursor..]);
        Ok(expanded)
    }

    fn expand(&mut self, source: &str) -> Result<String> {
        let content = read_text(&self.project.source_path(source)?)?;
        let mut expanded = String::new();
        let mut cursor = 0;

        for include in &self.graph.includes[source] {
            expanded.push_str(&content[cursor..include.start]);
            cursor = include.end;

            if include.system {
                self.system_headers.insert(include.name.clone());
            } else if let Some(generated) = self.generated.get(&include.name) {
                writeln!(expanded, "/* Generated include: {} */", include.name).unwrap();
                expanded.push_str(&self.expand_generated(generated)?);
            } else if self.seen.insert(include.name.clone()) {
                let header = self.expand(&include.name)?;
                self.headers.push((&include.name, header));
            }
        }

        expanded.push_str(&content[cursor..]);

        strip_pragma_once(&expanded).map_err(|error| format!("Could not expand {source}: {error}"))
    }
}

pub fn render(
    project: &Project,
    entries: &[String],
    generated: &BTreeMap<String, String>,
) -> Result<Rendered> {
    render_with_order(project, entries, generated, None)
}

/// Render with an optional section priority for implementations and self-contained headers.
pub fn render_with_order(
    project: &Project,
    entries: &[String],
    generated: &BTreeMap<String, String>,
    order: Option<SectionOrder>,
) -> Result<Rendered> {
    let graph = project.resolve(entries)?;
    let module_names = module_names(&graph.sources)?;

    for name in &graph.generated {
        if !generated.contains_key(name) {
            return Err(format!("Generated include is not prepared: {name}"));
        }
    }

    let mut expander = Expander {
        project,
        graph: &graph,
        generated,
        headers: Vec::new(),
        seen: BTreeSet::new(),
        system_headers: BTreeSet::new(),
    };

    let mut bodies = BTreeMap::new();

    // Collect headers in expansion order for projects with cyclic includes.
    for source in &graph.sources {
        bodies.insert(source.as_str(), expander.expand(source)?);
    }

    let mut text = String::from("/* Generated by c-source-bundle. */\n");

    for header in &expander.system_headers {
        writeln!(text, "#include <{header}>").unwrap();
    }

    let headers = &expander.headers;
    let header_order = match order {
        Some(order) => {
            let names: Vec<_> = headers.iter().map(|&(name, _)| name).collect();
            ordered_headers(&graph, &names, order)
        }
        None => (0..headers.len()).collect(),
    };

    for index in header_order {
        let (name, header) = &headers[index];
        writeln!(text, "\n/* ===== {name} ===== */").unwrap();
        writeln!(text, "{header}").unwrap();
    }

    for source in ordered_sources(&graph, order) {
        let body = &bodies[source];
        let name = &module_names[source];

        writeln!(text, "\n/* ===== Module: {name} =====").unwrap();
        writeln!(text, " * Source: {source}").unwrap();

        let scanner = Scanner::new(body).map_err(|e| format!("Could not qualify {source}: {e}"))?;
        let locals = scanner.private_names();

        if !locals.is_empty() {
            text.push_str(" * Identifier mapping:\n");

            for local in locals {
                writeln!(text, " *   {local} -> {name}__{local}").unwrap();
            }
        }

        text.push_str(" */\n");
        writeln!(text, "{}", scanner.rewrite(body, &format!("{name}__"))?).unwrap();
    }

    Ok(Rendered {
        text,
        generated: generated.clone(),
        graph,
    })
}
